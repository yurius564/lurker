  static #cache = new Map();

  /** Lit pixels of a skill's art as [x, y] (cached) */
  static pixels(id) {
    if(!CardArts.#cache.has(id))
      CardArts.#cache.set(id, (CardArts.ART[id] ?? []).flatMap((row, y) => [...row].flatMap((ch, x) => ch === '#'? [[x, y]]: [])));
    return CardArts.#cache.get(id);
  }

  /** Draw a skill's art with its top-left at x, y */
  static draw(ctx, id, x, y, color) {
    ctx.fillStyle = color;
    CardArts.pixels(id).forEach(([px, py]) => ctx.fillRect(x + px, y + py, 1, 1));
  }
